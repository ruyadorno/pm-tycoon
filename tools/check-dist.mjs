// Playtest build check (plan.md §6.11 budget, §12.7 task 3; plan-build2 §8.2 task 8): run after `vlr build`.
//   node tools/check-dist.mjs [distDir] [--json]
// Asserts on <distDir> (default dist/):
//   - the transfer size (every file the game can fetch: *.map excluded, the dev-only art gallery excluded)
//     is ≤ 8 MB uncompressed (Q-B2-10; 6 MB in build 1) — the worst case, `python3 -m http.server` sends no
//     gzip — and prints the gzip estimate a CDN/GitHub Pages would send (text types gzipped, PNG/MP3 raw);
//   - index.html uses relative asset URLs (vite base './', so the zip works at / and Pages under /pm-tycoon/);
//   - the content-hashed game assets (report-playtest1 §6.21; src/assets/* imported with `?url` by
//     src/render/assetUrls.ts): assets/world-<hash>.{png,json} and assets/interior-<hash>.{png,json} (each
//     PNG ≤ 2048², each JSON naming its frames), assets/m5x7-<hash>.xml, assets/logo-<hash>.png and
//     assets/attract-<hash>.json, each exactly once and each named by a JS chunk (the bundle pairs with
//     those bytes); no unhashed assets/world.png / world.json / m5x7.xml (the playtest-1 public/assets/
//     copies) in dist/, and no public/assets/ in the repo;
//   - configs/spicy.json (valid JSON, identical to public/configs/spicy.json), every vendored sample of
//     public/audio/sf/ (same bytes count) + LICENSE.txt, and playtest-README.txt are present.
// Lists the biggest files, the JS chunks with gzip estimates against the §6.11 targets, the samples, and any
// dev-only files that slipped into dist/ (public/gallery/ is gitignored but copied when it exists locally).
// Sourcemaps stay in the build (sourcemap: true): browsers fetch them only with devtools open, so the budget
// excludes them. Exit 1 on any failure.
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs'
import { dirname, join, relative, resolve, sep } from 'node:path'
import { fileURLToPath } from 'node:url'
import { gzipSync } from 'node:zlib'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const BUDGET = 8_000_000
const ATLAS_MAX = 2048
/** The hashed game assets: [stem, ext] -> dist/assets/<stem>-<hash>.<ext> (src/render/assetUrls.ts). */
const HASHED = [
  ['world', 'png'],
  ['world', 'json'],
  ['interior', 'png'],
  ['interior', 'json'],
  ['m5x7', 'xml'],
  ['logo', 'png'],
  ['attract', 'json'],
]
const ATLASES = ['world', 'interior']
/** plan.md §6.11 targets, for the printout. */
const TARGETS = {
  phaserGz: 300_000,
  samplesMax: 3_000_000,
}
const TEXT_EXT = /\.(js|mjs|json|html|xml|txt|css|svg|map)$/i
const DEV_ONLY = (p) => p === 'gallery.html' || p.startsWith('gallery/')

const args = process.argv.slice(2)
const json = args.includes('--json')
const dist = resolve(args.find((a) => !a.startsWith('--')) ?? 'dist')

const failures = []
const warnings = []
const fail = (msg) => failures.push(msg)
const warn = (msg) => warnings.push(msg)

const mb = (n) => `${(n / 1e6).toFixed(2)} MB`
const kb = (n) => `${(n / 1e3).toFixed(1)} kB`
const pad = (s, n) => String(s).padEnd(n)
const lpad = (s, n) => String(s).padStart(n)

function walk(dir) {
  const out = []
  for (const name of readdirSync(dir)) {
    const abs = join(dir, name)
    const st = statSync(abs)
    if (st.isDirectory()) out.push(...walk(abs))
    else out.push({ abs, path: relative(dist, abs).split(sep).join('/') })
  }
  return out
}

function gzSize(abs, path) {
  return TEXT_EXT.test(path)
    ? gzipSync(readFileSync(abs), { level: 9 }).length
    : statSync(abs).size
}

/** PNG width/height from the IHDR chunk. */
function pngSize(abs) {
  const b = readFileSync(abs)
  if (b.length < 24 || b.toString('ascii', 12, 16) !== 'IHDR') return null
  return { w: b.readUInt32BE(16), h: b.readUInt32BE(20) }
}

if (!existsSync(join(dist, 'index.html'))) {
  console.error(
    `check-dist: ${relative(process.cwd(), dist) || dist}/index.html missing — run "vlr build" first`,
  )
  process.exit(1)
}

const files = walk(dist).map((f) => ({
  ...f,
  size: statSync(f.abs).size,
  gz: gzSize(f.abs, f.path),
}))
const maps = files.filter((f) => f.path.endsWith('.map'))
const devOnly = files.filter(
  (f) => !f.path.endsWith('.map') && DEV_ONLY(f.path),
)
const transfer = files.filter(
  (f) => !f.path.endsWith('.map') && !DEV_ONLY(f.path),
)
const sum = (list, k) => list.reduce((n, f) => n + f[k], 0)
const total = sum(transfer, 'size')
const totalGz = sum(transfer, 'gz')

if (total > BUDGET) {
  fail(`transfer ${mb(total)} > ${mb(BUDGET)} budget (Q-B2-10)`)
}
if (devOnly.length > 0) {
  warn(
    `${devOnly.length} dev-only gallery files in dist/ (${mb(sum(devOnly, 'size'))}; public/gallery/ is ` +
      'gitignored, generated by `vlr art:gallery`): excluded from the budget, but they ride along in the zip',
  )
}

// index.html: relative URLs only (base './').
const html = readFileSync(join(dist, 'index.html'), 'utf8')
const urls = [...html.matchAll(/\b(?:src|href)="([^"]+)"/g)].map((m) => m[1])
for (const u of urls) {
  if (u.startsWith('data:') || /^https?:/.test(u)) continue
  if (u.startsWith('/'))
    fail(`index.html: absolute URL ${u} breaks under /pm-tycoon/`)
}
if (html.includes('/src/main.ts'))
  fail('index.html still points at /src/main.ts (not a vite build)')
if (!urls.some((u) => /^\.\/assets\/index-[\w-]+\.js$/.test(u))) {
  fail('index.html: no ./assets/index-<hash>.js entry script')
}

// The content-hashed assets: atlases, font descriptor, logo, attract snapshot.
const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
const jsText = transfer
  .filter((f) => /^assets\/.+\.js$/.test(f.path))
  .map((f) => readFileSync(f.abs, 'utf8'))
  .join('\n')
/** dist path of each hashed asset, by `<stem>.<ext>` (null when missing). */
const hashed = {}
for (const [stem, ext] of HASHED) {
  const re = new RegExp(`^assets/${escapeRe(stem)}-[\\w-]{6,}\\.${ext}$`)
  const hits = transfer.filter((f) => re.test(f.path))
  const id = `${stem}.${ext}`
  hashed[id] = hits[0] ?? null
  if (hits.length === 0) fail(`assets/${stem}-<hash>.${ext} missing`)
  else if (hits.length > 1) {
    fail(
      `${hits.length} copies of ${id}: ${hits.map((f) => f.path).join(', ')}`,
    )
  }
  for (const f of hits) {
    const name = f.path.slice('assets/'.length)
    if (!jsText.includes(name))
      fail(`${f.path} is not referenced by any JS chunk`)
  }
  if (existsSync(join(dist, 'assets', id))) {
    fail(
      `assets/${id} is unhashed (a public/assets/ leftover; src/assets is the source)`,
    )
  }
}
if (existsSync(join(ROOT, 'public/assets'))) {
  fail(
    'public/assets/ exists: game assets live in src/assets/ (hashed by Vite, report §6.21)',
  )
}
/** Per atlas: PNG size ≤ 2048², JSON frame count. */
const atlases = {}
for (const key of ATLASES) {
  const png = hashed[`${key}.png`]
  const desc = hashed[`${key}.json`]
  if (!png || !desc) continue
  const size = pngSize(png.abs)
  if (!size) fail(`${png.path} is not a PNG`)
  else if (size.w > ATLAS_MAX || size.h > ATLAS_MAX) {
    fail(`${png.path} is ${size.w}×${size.h} > ${ATLAS_MAX}²`)
  }
  let frames = 0
  try {
    const j = JSON.parse(readFileSync(desc.abs, 'utf8'))
    frames = (j.textures ?? []).reduce((n, t) => n + (t.frames?.length ?? 0), 0)
  } catch (err) {
    fail(`${desc.path} is not JSON: ${err.message}`)
  }
  if (frames === 0) fail(`${desc.path} has no frames`)
  atlases[key] = {
    png: png.path,
    json: desc.path,
    w: size?.w ?? 0,
    h: size?.h ?? 0,
    bytes: png.size,
    jsonBytes: desc.size,
    jsonGz: desc.gz,
    frames,
  }
}

// configs/spicy.json (?debug=1&config=spicy, plan.md §13.4 "How to play").
const spicyDist = join(dist, 'configs/spicy.json')
const spicySrc = join(ROOT, 'public/configs/spicy.json')
if (!existsSync(spicyDist)) fail('configs/spicy.json missing')
else {
  try {
    JSON.parse(readFileSync(spicyDist, 'utf8'))
  } catch (err) {
    fail(`configs/spicy.json is not JSON: ${err.message}`)
  }
  if (
    existsSync(spicySrc) &&
    !readFileSync(spicySrc).equals(readFileSync(spicyDist))
  ) {
    fail('configs/spicy.json differs from public/configs/spicy.json')
  }
}

// The vendored samples (audio.md §8): every file of public/audio/sf/ is in dist/audio/sf/ with the same size.
const sfSrc = join(ROOT, 'public/audio/sf')
const sfDist = join(dist, 'audio/sf')
const samples = transfer.filter((f) => f.path.startsWith('audio/sf/'))
const mp3s = samples.filter((f) => f.path.endsWith('.mp3'))
const presets = samples.filter((f) => f.path.endsWith('.preset.json'))
if (!existsSync(sfDist)) fail('audio/sf/ missing')
else if (existsSync(sfSrc)) {
  const want = walk(sfSrc).map((f) => ({
    rel: relative(sfSrc, f.abs).split(sep).join('/'),
    size: statSync(f.abs).size,
  }))
  for (const w of want) {
    const d = join(sfDist, w.rel)
    if (!existsSync(d)) fail(`audio/sf/${w.rel} missing`)
    else if (statSync(d).size !== w.size)
      fail(`audio/sf/${w.rel} size differs from public/`)
  }
}
if (!existsSync(join(sfDist, 'LICENSE.txt')))
  fail('audio/sf/LICENSE.txt missing (CC-BY 3.0 notice)')
if (mp3s.length === 0) fail('no samples (audio/sf/**/*.mp3)')
const samplesBytes = sum(samples, 'size')
if (samplesBytes > TARGETS.samplesMax) {
  fail(
    `samples ${mb(samplesBytes)} > ${mb(TARGETS.samplesMax)} (audio.md §8.1)`,
  )
}

if (!existsSync(join(dist, 'playtest-README.txt'))) {
  fail('playtest-README.txt missing (public/playtest-README.txt)')
}
if (maps.length === 0)
  warn('no sourcemaps (vite.config.ts sets sourcemap: true)')

// JS chunks: phaser / director (audio) / index (main) / lazy ones.
const chunkName = (p) =>
  p.replace(/^assets\//, '').replace(/-[\w-]{8}\.js$/, '')
const chunks = transfer
  .filter((f) => /^assets\/.+\.js$/.test(f.path))
  .map((f) => ({
    name: chunkName(f.path),
    path: f.path,
    size: f.size,
    gz: f.gz,
  }))
  .toSorted((a, b) => b.size - a.size)
const phaser = chunks.find((c) => c.name === 'phaser')
if (!phaser) fail('no phaser chunk (vite.config.ts manualChunks)')
const ROLE = {
  phaser: 'engine',
  index: 'main (game code)',
  director: 'audio (Tone Transport + smplr + director), lazy',
  policy: 'scripted policy, only with ?policy=1',
  offline: 'offline audio render, debug only',
}

const biggest = transfer.toSorted((a, b) => b.size - a.size).slice(0, 12)
const report = {
  dist: relative(process.cwd(), dist) || '.',
  budget: BUDGET,
  transfer: { files: transfer.length, bytes: total, gzBytes: totalGz },
  maps: { files: maps.length, bytes: sum(maps, 'size') },
  devOnly: { files: devOnly.length, bytes: sum(devOnly, 'size') },
  chunks,
  atlases,
  hashed: Object.fromEntries(
    Object.entries(hashed).map(([k, f]) => [k, f ? f.path : null]),
  ),
  samples: {
    mp3: mp3s.length,
    presets: presets.length,
    bytes: samplesBytes,
  },
  biggest: biggest.map((f) => ({ path: f.path, bytes: f.size, gz: f.gz })),
  warnings,
  failures,
  pass: failures.length === 0,
}

if (json) {
  console.log(JSON.stringify(report, null, 2))
} else {
  console.log(`check-dist: ${report.dist}`)
  console.log(
    `  transfer   ${mb(total)} raw (python http.server) · ~${mb(totalGz)} gzip (Pages/CDN) · ` +
      `${transfer.length} files · budget ${mb(BUDGET)} (Q-B2-10)`,
  )
  console.log(
    `  excluded   ${maps.length} sourcemaps ${mb(report.maps.bytes)} (fetched only with devtools open)` +
      (devOnly.length
        ? ` · ${devOnly.length} dev-only gallery files ${mb(report.devOnly.bytes)}`
        : ''),
  )
  console.log('  JS chunks                    raw        gzip   role')
  for (const c of chunks) {
    console.log(
      `    ${pad(c.name, 22)} ${lpad(kb(c.size), 10)} ${lpad(kb(c.gz), 10)}   ${ROLE[c.name] ?? ''}`,
    )
  }
  if (phaser) {
    console.log(
      `    phaser gzip ${kb(phaser.gz)} vs the §6.11 estimate ~${kb(TARGETS.phaserGz)}`,
    )
  }
  for (const [key, a] of Object.entries(report.atlases)) {
    console.log(
      `  atlas      ${pad(key, 8)} ${a.w}×${a.h} ${kb(a.bytes)} (≤ ${ATLAS_MAX}²) · ${a.frames} frames · ` +
        `json ${kb(a.jsonBytes)} (gzip ${kb(a.jsonGz)})`,
    )
  }
  console.log(
    `  hashed     ${Object.values(report.hashed)
      .map((p) => (p ? p.replace(/^assets\//, '') : 'MISSING'))
      .join(' · ')}`,
  )
  console.log(
    `  samples    ${mp3s.length} mp3 + ${presets.length} presets ${mb(samplesBytes)} ` +
      `(≤ ${mb(TARGETS.samplesMax)}, audio.md §8.1) · spicy.json ${existsSync(spicyDist) ? 'present' : 'MISSING'}`,
  )
  console.log('  biggest files (transfer set)')
  for (const f of biggest) {
    console.log(
      `    ${pad(f.path, 44)} ${lpad(kb(f.size), 10)} ${lpad(kb(f.gz), 10)}`,
    )
  }
  for (const w of warnings) console.log(`  WARN  ${w}`)
  for (const f of failures) console.log(`  FAIL  ${f}`)
  console.log(`check-dist: ${report.pass ? 'PASS' : 'FAIL'}`)
}
process.exit(report.pass ? 0 : 1)
