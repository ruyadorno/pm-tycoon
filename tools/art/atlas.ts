// `vlr art:atlas` (style-guide.md §3.7 atlas, §7; plan.md §5 "Atlas and
// frames"): ONE atlas `world` = public/assets/world.png + world.json
// (free-tex-packer-core, exporter Phaser3 = JSON with textures[].frames[],
// loaded by this.load.atlas; padding 1, extrude 1, power of two, max 2048,
// no rotation) holding every final incl. `_locked` variants, the UI
// nine-slices and the m5x7 glyph sheet (art/final/font/m5x7.png when
// `vlr font:build` produced it).
//
// Trimming: only the big mostly-transparent city sprites (building*,
// warehouse-ext, prop, dock-prop) are trimmed — here, before packing, so
// the result is exact and deterministic; their frames carry trimmed: true,
// sourceSize = the class canvas and spriteSourceSize = the kept rect, so
// setOrigin(0.5, 1) still means the canvas bottom-centre. Tiles (stamped
// into the ground bake), nine-slices, icons and the font are never trimmed.
//
// Also emits src/render/frames.generated.ts (FRAMES, FrameName and typed
// helpers: a missing frame is a type error) and
// src/render/spriteMap.generated.json (buildings.json id -> sprite id,
// locked scenery through coversBuildings). If everything does not fit one
// 2048^2 page the step fails (A08) and names what overflowed.

import { existsSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { packAsync } from 'free-tex-packer-core'
import type { StepOpts } from './draw-api.ts'
import { SIGN_FACE, SIGN_LOCKED_FACE } from './exterior.ts'
import { bbox, encodeImg, newImg, readImg, writeIfChanged } from './iso.ts'
import {
  type AssetClass,
  type Manifest,
  type ManifestEntry,
  ROOT,
  buildingCoverage,
  finalPath,
  frameNames,
  loadBuildingIds,
  loadManifest,
} from './manifest.ts'

export const ATLAS_PNG = join(ROOT, 'public/assets/world.png')
export const ATLAS_JSON = join(ROOT, 'public/assets/world.json')
export const FRAMES_TS = join(ROOT, 'src/render/frames.generated.ts')
export const SPRITE_MAP_JSON = join(ROOT, 'src/render/spriteMap.generated.json')
export const MAX_SIDE = 2048

const TRIM_CLASSES: readonly AssetClass[] = [
  'building1x1',
  'building2x2',
  'building3x3',
  'warehouse-ext',
  'prop',
  'dock-prop',
]

interface Item {
  name: string
  entry: ManifestEntry
  buf: Buffer
  trim: {
    x: number
    y: number
    w: number
    h: number
    sw: number
    sh: number
  } | null
}

function collect(m: Manifest): { items: Item[]; missing: string[] } {
  const items: Item[] = []
  const missing: string[] = []
  for (const e of m.entries) {
    for (const name of frameNames(e)) {
      const p = finalPath(e, name)
      if (!existsSync(p)) {
        missing.push(name)
        continue
      }
      if (!TRIM_CLASSES.includes(e.class)) {
        items.push({ name, entry: e, buf: readFileSync(p), trim: null })
        continue
      }
      const { img } = readImg(p)
      const b = bbox(img) ?? { x0: 0, y0: 0, x1: 0, y1: 0 }
      const w = b.x1 - b.x0 + 1
      const h = b.y1 - b.y0 + 1
      const crop = newImg(w, h)
      for (let y = 0; y < h; y++) {
        for (let x = 0; x < w; x++) {
          crop.px[y * w + x] = img.px[(b.y0 + y) * img.w + b.x0 + x] as number
        }
      }
      items.push({
        name,
        entry: e,
        buf: encodeImg(crop),
        trim: { x: b.x0, y: b.y0, w, h, sw: img.w, sh: img.h },
      })
    }
  }
  return {
    items: items.toSorted((a, b) =>
      a.name < b.name ? -1 : a.name > b.name ? 1 : 0,
    ),
    missing,
  }
}

interface PhaserFrame {
  filename: string
  rotated: boolean
  trimmed: boolean
  sourceSize: { w: number; h: number }
  spriteSourceSize: { x: number; y: number; w: number; h: number }
  frame: { x: number; y: number; w: number; h: number }
}

interface PhaserAtlas {
  textures: {
    image: string
    format: string
    size: { w: number; h: number }
    scale: number
    frames: PhaserFrame[]
  }[]
  meta: Record<string, unknown>
}

function pow2(n: number): boolean {
  return n > 0 && (n & (n - 1)) === 0
}

